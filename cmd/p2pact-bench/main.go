// Command p2pact-bench compares P2PACT (over UDP and TCP) with WebSocket and HTTPS+JSON: bytes
// on the wire and time for chat messages of several sizes over emulated links.
//
//	p2pact-bench run [-out results] [-repeat N] [-seed N] [-data SPEC] [-remote HOST] scenarios/*.json
//	p2pact-bench serve [-bind 0.0.0.0] [-advertise HOST]   the receivers, for -remote (ports 48731–48736)
//	p2pact-bench data                 list the open datasets and the cache directory
//	p2pact-bench report               rebuild the Markdown tables and SUMMARY.md from the saved results
//	p2pact-bench samples DIR          write the training half of the common dictionary's sources as
//	                                  files, for zstd --train -r DIR --maxdict=65536 --dictID=1345470787
//	                                  -o common-1.zdict
//
// Without -remote everything runs on this machine over emulated links. With -remote HOST the
// receivers run on HOST (`p2pact-bench serve` there) and the network is real: the scenario's
// profiles are replaced by one, "real network".
//
// A scenario is a JSON file (see scenarios/). To try a variation, copy one and change any
// field: profiles, size bins, protocols, data, repetitions, seed. Flags override the files.
// Each run writes <out>/<scenario>.md and .json, and <out>/RESULTS.md with all of them.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"math/rand"
	"os"
	"path/filepath"
	"strings"

	p2pact "github.com/p2pact/p2pact-go"
	bench "github.com/p2pact/p2pact-tests"
)

func main() {
	if len(os.Args) < 2 {
		usage()
	}
	switch os.Args[1] {
	case "run":
		run(os.Args[2:])
	case "serve":
		serve(os.Args[2:])
	case "report":
		rebuild()
	case "samples":
		if len(os.Args) != 3 {
			usage()
		}
		samples(os.Args[2])
	case "data":
		fmt.Println("cache:", bench.CacheDir())
		for _, d := range bench.Datasets {
			fmt.Printf("- %s (%s): %s\n  %s\n", d.Name, d.License, d.Title, d.URL)
		}
		fmt.Println("data specs: synthetic, oasst2:human, oasst2:assistant, oasst2:human:<lang>, swe-gym:agent, swe-gym:tool, file:<path to a JSON array of strings>")
	default:
		usage()
	}
}

func usage() {
	fmt.Fprintln(os.Stderr, "usage: p2pact-bench run [-out dir] [-repeat N] [-seed N] [-data SPEC] [-dict=false] scenario.json…\n       p2pact-bench data\n       p2pact-bench samples DIR")
	os.Exit(2)
}

func run(args []string) {
	fs := flag.NewFlagSet("run", flag.ExitOnError)
	out := fs.String("out", "results", "where to write reports")
	repeat := fs.Int("repeat", 0, "override: messages per size")
	seed := fs.Int64("seed", 0, "override: seed")
	data := fs.String("data", "", "override: data source")
	remote := fs.String("remote", "", "host running `p2pact-bench serve`: measure over the real network")
	dict := fs.Bool("dict", true, "give P2PACT nodes the common dictionary")
	_ = fs.Parse(args)
	if fs.NArg() == 0 {
		usage()
	}
	bench.UseDict = *dict
	if err := os.MkdirAll(*out, 0o755); err != nil {
		fail(err)
	}
	var all []string
	failed := false
	for _, path := range fs.Args() {
		sc, err := bench.LoadScenario(path)
		if err != nil {
			fail(err)
		}
		if *repeat > 0 {
			sc.Repeat = *repeat
		}
		if *seed != 0 {
			sc.Seed = *seed
		}
		if *data != "" {
			sc.Data = *data
		}
		var t *bench.Target
		stop := func() {}
		if *remote != "" {
			t = bench.RemoteTarget(*remote)
			sc.Profiles = []bench.Profile{{Name: "real network"}}
		} else if t, stop, err = bench.LocalTarget(); err != nil {
			fail(err)
		}
		fmt.Fprintf(os.Stderr, "== %s\n", sc.Name)
		rep, err := bench.Execute(sc, t, os.Stderr)
		stop()
		if err != nil { // one failed scenario (a download, say) does not stop the rest
			fmt.Fprintf(os.Stderr, "%s: %v\n", sc.Name, err)
			failed = true
			continue
		}
		base := filepath.Join(*out, strings.TrimSuffix(filepath.Base(path), ".json"))
		md := rep.Markdown()
		js, _ := json.MarshalIndent(rep, "", "  ")
		if err := os.WriteFile(base+".md", []byte(md), 0o644); err != nil {
			fail(err)
		}
		if err := os.WriteFile(base+".json", js, 0o644); err != nil {
			fail(err)
		}
		all = append(all, md)
		fmt.Print(md)
	}
	head := "# P2PACT benchmark results\n\nGenerated by `p2pact-bench run`. Every number can be reproduced: the scenario files are in " +
		"`scenarios/`, the method in `README.md` of https://github.com/p2pact/p2pact-tests.\n\n"
	if err := os.WriteFile(filepath.Join(*out, "RESULTS.md"), []byte(head+strings.Join(all, "\n")), 0o644); err != nil {
		fail(err)
	}
	if failed {
		os.Exit(1)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func serve(args []string) {
	fs := flag.NewFlagSet("serve", flag.ExitOnError)
	bind := fs.String("bind", "0.0.0.0", "address to listen on")
	advertise := fs.String("advertise", "", "public address to announce to P2PACT clients")
	dir := fs.String("dir", filepath.Join(os.TempDir(), "p2pact-bench-server"), "server keys")
	_ = fs.Parse(args)
	s, err := bench.StartServers(*dir, *bind, bench.BasePort)
	if err != nil {
		fail(err)
	}
	if *advertise != "" {
		a := fmt.Sprintf("%s:%d", *advertise, bench.BasePort)
		s.Node.SetAdvertise(&p2pact.Hints{UDP: []string{a}, TCP: []string{a}})
	}
	fmt.Printf("p2pact-bench receivers: P2PACT %s (udp+tcp), WebSocket %s, HTTPS %s, HTTP/2 %s, gRPC %s, HTTP/3 %s\n",
		s.P2PUDP, s.WS, s.HTTPS, s.HTTP2, s.GRPC, s.HTTP3)
	select {}
}

// rebuild regenerates results*/<scenario>.md, results*/RESULTS.md and SUMMARY.md from the
// saved JSON reports, without measuring again.
func rebuild() {
	for _, dir := range []string{"results-real", "results"} {
		files, _ := filepath.Glob(filepath.Join(dir, "*.json"))
		var all []string
		for _, f := range files {
			rep, err := bench.LoadReport(f)
			if err != nil {
				fail(err)
			}
			md := rep.Markdown()
			if err := os.WriteFile(strings.TrimSuffix(f, ".json")+".md", []byte(md), 0o644); err != nil {
				fail(err)
			}
			all = append(all, md)
		}
		if len(all) > 0 {
			head := "# P2PACT benchmark results\n\nGenerated by `p2pact-bench`. Every number can be reproduced: the scenario files are in " +
				"`scenarios/`, the method in `README.md` of https://github.com/p2pact/p2pact-tests.\n\n"
			if err := os.WriteFile(filepath.Join(dir, "RESULTS.md"), []byte(head+strings.Join(all, "\n")), 0o644); err != nil {
				fail(err)
			}
		}
	}
	sum, err := bench.Summary("results-real", "results")
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile("SUMMARY.md", []byte(sum), 0o644); err != nil {
		fail(err)
	}
	fmt.Println("rebuilt results-real/, results/ and SUMMARY.md")
}

// samples writes the training half of the common dictionary's sources: equal bytes per source, each text cut
// to 4 KB (a dictionary helps the start of a message most), in a seeded order.
func samples(dir string) {
	texts, err := bench.TrainingTexts(bench.CommonSources, os.Stderr)
	if err != nil {
		fail(err)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		fail(err)
	}
	const perSource, cut = 4 << 20, 4 << 10
	for src, msgs := range texts {
		r := rand.New(rand.NewSource(1))
		r.Shuffle(len(msgs), func(i, j int) { msgs[i], msgs[j] = msgs[j], msgs[i] })
		total := 0
		name := strings.ReplaceAll(src, ":", "-")
		for i, m := range msgs {
			if total >= perSource {
				break
			}
			if len(m) > cut {
				m = m[:cut]
			}
			total += len(m)
			if err := os.WriteFile(filepath.Join(dir, fmt.Sprintf("%s-%06d.txt", name, i)), []byte(m), 0o644); err != nil {
				fail(err)
			}
		}
		fmt.Fprintf(os.Stderr, "%s: %d texts, %d bytes\n", src, min(len(msgs), 1<<30), total)
	}
}
